// Builds the store images from template-images/<folder>/ into light WebP copies in public/ti/,
// and writes lib/local-images.ts:
//  - LOCAL: image key -> [url base, available widths, has alpha]
//      key = Unsplash photo id for downloaded photos ("1594035910387-fea47794261f"),
//            "<folder>/<name>" for hero cutouts and other added images ("cx-asal/hero")
//  - HEROES: template id -> hero keys (folder "cx-dahab" -> template "dahab")
// Runs automatically before `next dev` / `next build` (see package.json); unchanged images are skipped.
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "template-images", OUT = "public/ti";
const WIDTHS = [480, 960, 1600];
const IMG = /\.(jpe?g|png|webp|avif)$/i;
const byName = (a, b) => a.localeCompare(b, "en", { numeric: true });

let sharp = null;
try { sharp = (await import("sharp")).default; } catch { console.warn("local-images: sharp not found — images will not be optimised"); }

const local = {}, heroes = {};
let made = 0;
for (const folder of readdirSync(SRC).sort()) {
  const dir = join(SRC, folder);
  if (!statSync(dir).isDirectory()) continue;
  const tpl = folder.replace(/^cx-/, "");
  mkdirSync(join(OUT, folder), { recursive: true });
  for (const file of readdirSync(dir).sort(byName)) {
    if (!IMG.test(file)) continue;
    const name = file.replace(IMG, "");
    const isHero = /^hero\d*$/i.test(name);
    const isPhoto = /^\d+-[0-9a-f]+$/i.test(name);
    // Unsplash-named photos are keyed by their photo id; heroes and any other added image by "<folder>/<name>"
    const key = isPhoto ? name : `${folder}/${name}`;
    if (local[key]) continue;
    const src = join(dir, file), base = `/ti/${folder}/${name}`;
    if (!sharp) {
      copyFileSync(src, join(OUT, folder, file));
      local[key] = [`/ti/${folder}/${file}`, [], isHero];
    } else {
      const meta = await sharp(src).metadata();
      const ws = WIDTHS.filter((w) => w < meta.width).concat(Math.min(meta.width, WIDTHS.at(-1))).filter((w, i, a) => a.indexOf(w) === i);
      for (const w of ws) {
        const out = join(OUT, folder, `${name}-${w}.webp`);
        if (existsSync(out) && statSync(out).mtimeMs >= statSync(src).mtimeMs) continue;
        await sharp(src).resize({ width: w, withoutEnlargement: true }).webp({ quality: meta.hasAlpha ? 80 : 72, effort: 5, alphaQuality: 90 }).toFile(out);
        made++;
      }
      local[key] = [base, ws, !!meta.hasAlpha];
    }
    if (isHero) (heroes[tpl] ??= []).push(key);
  }
}

const out = `// Generated by scripts/gen-local-images.mjs — do not edit by hand.
/** key -> [url base, widths ("<base>-<w>.webp"), transparent cutout] */
export const LOCAL: Record<string, [string, number[], boolean]> = ${JSON.stringify(local)};
export const HEROES: Record<string, string[]> = ${JSON.stringify(heroes)};
`;
writeFileSync("lib/local-images.ts", out);
console.log(`local-images: ${Object.keys(local).length} images, ${Object.values(heroes).flat().length} hero cutouts, ${made} files written`);
